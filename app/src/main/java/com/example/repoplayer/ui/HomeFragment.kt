package com.example.repoplayer.ui

import android.os.Bundle
import android.view.LayoutInflater
import android.view.View
import android.view.ViewGroup
import android.widget.Button
import androidx.fragment.app.Fragment
import com.example.repoplayer.R

class HomeFragment : Fragment() {

    override fun onCreateView(
        inflater: LayoutInflater,
        container: ViewGroup?,
        savedInstanceState: Bundle?
    ): View? {
        return inflater.inflate(R.layout.fragment_home, container, false)
    }

    override fun onViewCreated(view: View, savedInstanceState: Bundle?) {
        super.onViewCreated(view, savedInstanceState)
        val repoButton = view.findViewById<Button>(R.id.repoButton)
        val settingsButton = view.findViewById<Button>(R.id.settingsButton)

        repoButton.setOnClickListener {
            (requireActivity() as MainActivity).showRepositories()
        }

        settingsButton.setOnClickListener {
            (requireActivity() as MainActivity).showSettings()
        }
    }
}

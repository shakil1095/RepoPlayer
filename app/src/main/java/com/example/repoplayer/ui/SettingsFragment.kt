package com.example.repoplayer.ui

import android.os.Bundle
import android.view.LayoutInflater
import android.view.View
import android.view.ViewGroup
import android.widget.Button
import android.widget.TextView
import androidx.fragment.app.Fragment
import com.example.repoplayer.R
import com.google.android.material.switchmaterial.SwitchMaterial

class SettingsFragment : Fragment() {

    override fun onCreateView(
        inflater: LayoutInflater,
        container: ViewGroup?,
        savedInstanceState: Bundle?
    ): View? {
        return inflater.inflate(R.layout.fragment_settings, container, false)
    }

    override fun onViewCreated(view: View, savedInstanceState: Bundle?) {
        super.onViewCreated(view, savedInstanceState)
        val darkModeSwitch = view.findViewById<SwitchMaterial>(R.id.darkModeSwitch)
        darkModeSwitch.isChecked = com.example.repoplayer.data.store.RepoPreferences(requireContext()).isDarkModeEnabled()
        darkModeSwitch.setOnCheckedChangeListener { _, isChecked ->
            com.example.repoplayer.data.store.RepoPreferences(requireContext()).setDarkMode(isChecked)
        }
    }
}
